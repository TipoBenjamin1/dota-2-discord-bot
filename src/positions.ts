export function positionFit(hero: OpenDotaHero, position: Position): number {
  const knownPositionFit = heroPositionWeights[hero.localized_name];
  if (knownPositionFit) {
    return knownPositionFit[position] ?? 0;
  }

  const weights = roleWeights[position];
  return hero.roles.reduce((sum, role) => sum + (weights[role] ?? 0), 0);
}

export function heroCanPlayPosition(hero: OpenDotaHero, position: Position): boolean {
  return positionFit(hero, position) >= 0.35;
}
